# Offline-only font baking. Inter is distributed under SIL OFL, see art/fonts/OFL.txt.
# Each face is baked at several UI scales so Obsidian can draw at the panel's
# native resolution (1x = the 1104x723 design canvas; 2.5x ~ 2944x1840).
from pathlib import Path
import math
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
font_path = root / "art/fonts/Inter.ttf"
codepoints = list(range(32, 127)) + [0x2191, 0x2193, 0x2190, 0x2192, 0xB7]
faces = [(16, 400), (22, 500), (32, 500)]
scales = [1.0, 1.5, 2.0, 2.5, 3.0]
pixels, offsets, widths, advances, heights = [], [], [], [], []
for scale in scales:
    s_offsets, s_widths, s_advances, s_heights = [], [], [], []
    for size, weight in faces:
        font = ImageFont.truetype(str(font_path), size=round(size * scale * 2))
        font.set_variation_by_axes([32, weight])
        ascent, descent = font.getmetrics()
        height = math.ceil((ascent + descent) / 2)
        s_heights.append(height)
        f_offsets, f_widths, f_advances = [], [], []
        for cp in codepoints:
            char = chr(cp)
            advance = font.getlength(char) / 2
            width = math.ceil(advance) + 2
            image = Image.new("L", (width * 2, height * 2))
            ImageDraw.Draw(image).text((0, ascent), char, font=font, fill=255, anchor="ls")
            image = image.resize((width, height), Image.Resampling.LANCZOS)
            f_offsets.append(len(pixels))
            f_widths.append(width)
            f_advances.append(round(advance * 64))
            pixels.extend(image.tobytes())
        s_offsets.append(f_offsets)
        s_widths.append(f_widths)
        s_advances.append(f_advances)
    offsets.append(s_offsets)
    widths.append(s_widths)
    advances.append(s_advances)
    heights.append(s_heights)

def row(values):
    return "{" + ",".join(map(str, values)) + "}"

def table(sets):
    return "{" + ",\n".join("{" + ",\n".join(map(row, faces_)) + "}" for faces_ in sets) + "}"

n = len(codepoints)
header = [
    "// SPDX-License-Identifier: OFL-1.1",
    "// SPDX-FileCopyrightText: 2020 The Inter Project Authors",
    "// GENERATED by conn/tools/bake_obsidian_font.py; do not edit.",
    "// Inter glyph data: SIL Open Font License 1.1, conn/art/fonts/OFL.txt.",
    "#ifndef CONN_OBSIDIAN_FONT_H", "#define CONN_OBSIDIAN_FONT_H",
    f"#define OBS_FONT_GLYPHS {n}",
    f"#define OBS_FONT_SETS {len(scales)}",
    "/* UI scale of each set in 1/1024 units (1024 = 1104x723 design canvas). */",
    "static const UINT32 obs_font_set_scale[OBS_FONT_SETS] = "
    + row([round(s * 1024) for s in scales]) + ";",
    "static const UINT32 obs_font_cp[] = " + row(codepoints) + ";",
    "static const UINT8 obs_font_height[OBS_FONT_SETS][3] = {" + ",".join(map(row, heights)) + "};",
    "static const UINT32 obs_font_offset[OBS_FONT_SETS][3][OBS_FONT_GLYPHS] = " + table(offsets) + ";",
    "static const UINT8 obs_font_width[OBS_FONT_SETS][3][OBS_FONT_GLYPHS] = " + table(widths) + ";",
    "static const UINT16 obs_font_advance[OBS_FONT_SETS][3][OBS_FONT_GLYPHS] = " + table(advances) + ";",
    "static const UINT8 obs_font_pixels[] = {",
]
header += [",".join(map(str, pixels[i:i+160])) + "," for i in range(0, len(pixels), 160)]
header += ["};", "#endif"]
target = root / "core/obsidian_font.h"
target.write_text("\n".join(header) + "\n", encoding="utf-8")
print(f"Wrote {target}: {len(pixels)} coverage bytes, max width {max(max(max(f) for f in s) for s in widths)}, heights {heights}")
